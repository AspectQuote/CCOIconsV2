export function getElementSpriteSheetPosition(elementID) {
    const foundIndex = elementSpriteSheetLayout.findIndex(material => material === elementID);
    if (foundIndex === -1) {
        return {
            x: 0,
            y: 0
        };
    }
    else {
        return {
            x: (foundIndex % elementSpriteSheetSize),
            y: Math.floor(foundIndex / elementSpriteSheetSize)
        };
    }
}
